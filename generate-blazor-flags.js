// Writes Components/Shared/CountryFlags.g.cs: the flag pictograms from the Pixl editor's document
// (indx-pixl's pixl.json, artboards "pictograms / ..."), keyed by the region code a language tag
// carries ("nb-NO" -> NO). Pictograms are not in the pixl npm package until 2.0, so the console
// takes them from the document directly. The flags keep their own colours; the white is fixed.
//
//   node IndxServer/generate-blazor-flags.js [path/to/pixl.json]
const fs = require('fs');
const path = require('path');

const source = process.argv[2] ?? path.join(__dirname, '..', '..', '..', 'Web', 'indx-pixl', 'pixl.json');
const output = path.join(__dirname, 'Components', 'Shared', 'CountryFlags.g.cs');

// Pictogram name -> region code (ISO 3166-1, as a language tag's region subtag spells it). England
// and Scotland have no region code of their own, so they are left out. "sami" is not a region: the
// Sámi languages get the flag of Sápmi whatever region they name.
const CODES = {
  'norwegian flag': 'NO', 'swedish flag': 'SE', 'danish flag': 'DK', 'finnish flag': 'FI',
  'icelandic flag': 'IS', 'faroese flag': 'FO', 'aland flag': 'AX', 'sami flag': 'sami',
  'spanish flag': 'ES', 'french flag': 'FR', 'italian flag': 'IT', 'german flag': 'DE',
  'dutch flag': 'NL', 'ukrainian flag': 'UA', 'polish flag': 'PL', 'swiss flag': 'CH',
  'eu flag': 'EU', 'uk flag': 'GB', 'irish flag': 'IE', 'belgian flag': 'BE', 'romanian flag': 'RO',
  'austrian flag': 'AT', 'latvian flag': 'LV', 'hungarian flag': 'HU', 'russian flag': 'RU',
  'bulgarian flag': 'BG', 'lithuanian flag': 'LT', 'estonian flag': 'EE', 'luxembourg flag': 'LU',
  'czech flag': 'CZ', 'portuguese flag': 'PT', 'greek flag': 'GR', 'japanese flag': 'JP',
  'us flag': 'US', 'canadian flag': 'CA', 'mexican flag': 'MX', 'cuban flag': 'CU',
  'puerto rican flag': 'PR', 'brazilian flag': 'BR', 'argentine flag': 'AR', 'uruguayan flag': 'UY',
  'colombian flag': 'CO', 'chilean flag': 'CL', 'peruvian flag': 'PE', 'jamaican flag': 'JM',
  'chinese flag': 'CN', 'south korean flag': 'KR', 'indian flag': 'IN', 'thai flag': 'TH',
  'vietnamese flag': 'VN', 'bangladeshi flag': 'BD', 'indonesian flag': 'ID', 'australian flag': 'AU',
  'new zealand flag': 'NZ', 'turkish flag': 'TR', 'israeli flag': 'IL', 'lebanese flag': 'LB',
  'emirati flag': 'AE', 'egyptian flag': 'EG', 'moroccan flag': 'MA', 'nigerian flag': 'NG',
  'ghanaian flag': 'GH', 'kenyan flag': 'KE',
};

const doc = JSON.parse(fs.readFileSync(source, 'utf8'));
const colors = new Map(doc.colors.map((c) => [c.id, c]));
// A palette colour's light value, following references ("c:<id>") to the hex they end in.
function hex(fill) {
  let id = fill.startsWith('c:') ? fill.slice(2) : null;
  for (let hops = 0; id && hops < 8; hops++) {
    const c = colors.get(id);
    if (!c) break;
    if (!c.light.startsWith('c:')) return c.light.toUpperCase();
    id = c.light.slice(2);
  }
  throw new Error(`No colour for ${fill}`);
}

const flags = new Map();
for (const board of doc.artboards) {
  if (board.kind !== 'pictograms' && board.kind !== 'illustrations') continue;
  for (const icon of board.icons) {
    const code = CODES[icon.name];
    if (!code || flags.has(code)) continue;
    if (icon.w !== 7 || icon.h !== 5) throw new Error(`${icon.name} is not 7 by 5`);
    const rects = icon.rects
      .map((r) => `<rect x="${r.x}" y="${r.y}" width="${r.w}" height="${r.h}" fill="${hex(r.fill)}"/>`)
      .join('');
    flags.set(code, { name: icon.name, rects });
  }
}
const missing = Object.entries(CODES).filter(([, code]) => !flags.has(code)).map(([name]) => name);
if (missing.length) console.warn(`Not in the document, left out: ${missing.join(', ')}`);

const lines = [...flags.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([code, f]) => `            ["${code}"] = "${f.rects.replace(/"/g, '\\"')}", // ${f.name}`);
const cs = `// <auto-generated>
// Written by generate-blazor-flags.js from the flag pictograms in indx-pixl's pixl.json. Do not
// edit by hand: change the flag in the Pixl editor and run the script again.
// </auto-generated>
namespace IndxServer.Components.Shared
{
    internal static class CountryFlags
    {
        /// <summary>The flags' 7 by 5 cells as SVG rects, by region code; "sami" for Sápmi.</summary>
        internal static readonly IReadOnlyDictionary<string, string> Rects = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
        {
${lines.join('\n')}
        };
    }
}
`;
fs.writeFileSync(output, cs);
console.log(`Wrote ${flags.size} flags to ${path.relative(process.cwd(), output)}`);
